//! Golden vectors for the RTL testbenches. Everything is generated from the Rust encoder and
//! the Rust models in this crate; nothing here is typed in by hand.
//!
//! * [`pattern_vectors_json`]   - for every event x zone x distance: packet bytes and pulses.
//! * [`pattern_rom_hex`]        - the same data as a `$readmemh` image for the pattern ROM.
//! * [`packet_vectors_json`]    - valid / invalid frames and byte streams for the UART parser.
//! * [`scheduler_vectors_json`] - timed scenarios with the expected pattern start times.

use std::fmt::Write;

use neurosight_encoder::SafetyLimits;

use crate::rom::{all_keys, pattern_for, rom_slot, rom_words, KEY_COUNT, WORDS_PER_KEY};
use crate::sched::run_schedule;
use crate::wire::{
    action_id, action_name, distance_code, frame, hex, zone_code, Key, Packet, PacketParser,
    Parsed,
};
use neurosight_common::{Action, Distance, Zone};

fn key_fields(key: &Key) -> String {
    format!(
        "\"action_id\":{},\"action\":\"{}\",\"zone\":{},\"distance\":{}",
        action_id(key.action).expect("supported action"),
        action_name(key.action),
        zone_code(key.zone),
        distance_code(key.distance)
    )
}

pub fn pattern_vectors_json(limits: &SafetyLimits) -> String {
    let mut rows = Vec::new();
    for key in all_keys() {
        let packet = Packet::new(key, 100).expect("supported action");
        let pattern = pattern_for(&key, limits);
        let pulses: Vec<String> = pattern
            .pulses
            .iter()
            .map(|p| {
                format!(
                    "{{\"ms\":{},\"motor\":{},\"duty\":{}}}",
                    p.offset_ms, p.motor, p.duty
                )
            })
            .collect();
        rows.push(format!(
            "  {{{},\"confidence\":100,\"packet\":\"{}\",\"duration_ms\":{},\"pulses\":[{}]}}",
            key_fields(&key),
            hex(&packet.encode()),
            pattern.duration_ms(),
            pulses.join(",")
        ));
    }
    format!(
        "{{\"format\":1,\"grid\":5,\"duty_full_scale\":255,\"max_pulses\":8,\"vectors\":[\n{}\n]}}\n",
        rows.join(",\n")
    )
}

pub fn pattern_rom_hex(limits: &SafetyLimits) -> String {
    let mut words = vec![0u32; KEY_COUNT * WORDS_PER_KEY];
    for key in all_keys() {
        let slot = rom_slot(&key);
        let image = rom_words(&pattern_for(&key, limits));
        words[slot * WORDS_PER_KEY..(slot + 1) * WORDS_PER_KEY].copy_from_slice(&image);
    }
    let mut out = String::new();
    out.push_str("// NeuroSight pattern ROM, generated by `export-vectors`. Do not edit.\n");
    out.push_str("// address = ((action_id - 1) * 3 + zone) * 3 + distance) * 9 + word\n");
    out.push_str("// word 0: [31:16] duration_ms, [7:0] pulse count\n");
    out.push_str("// words 1..8: [31:16] offset_ms, [15:8] motor, [7:0] duty\n");
    for w in words {
        let _ = writeln!(out, "{:08x}", w);
    }
    out
}

fn parsed_label(p: Parsed) -> Option<String> {
    match p {
        Parsed::Nothing => None,
        Parsed::Packet(packet) => Some(format!("ok:{}", hex(&packet.encode()))),
        Parsed::Error(e) => Some(format!("err:{}", e.name())),
    }
}

fn run_stream(bytes: &[u8]) -> Vec<String> {
    let mut parser = PacketParser::new();
    bytes
        .iter()
        .filter_map(|b| parsed_label(parser.feed(*b)))
        .collect()
}

fn quote_list(items: &[String]) -> String {
    items
        .iter()
        .map(|s| format!("\"{}\"", s))
        .collect::<Vec<_>>()
        .join(",")
}

pub fn packet_vectors_json() -> String {
    let wave = Packet::new(
        Key {
            action: Action::Waving,
            zone: Zone::Left,
            distance: Distance::Near,
        },
        83,
    )
    .unwrap()
    .encode();
    let nod = Packet::new(
        Key {
            action: Action::Nodding,
            zone: Zone::Center,
            distance: Distance::Medium,
        },
        60,
    )
    .unwrap()
    .encode();

    let mut bad_start = wave;
    bad_start[0] = 0x5A;
    let mut bad_sum = wave;
    bad_sum[5] ^= 0x01;

    // (name, bytes): each frame is fed byte by byte to the parser.
    let mut streams: Vec<(&str, Vec<u8>)> = Vec::new();
    streams.push(("single_valid", wave.to_vec()));
    streams.push(("two_valid_back_to_back", [wave, nod].concat()));
    streams.push(("leading_garbage", [vec![0x00, 0xFF, 0x12], wave.to_vec()].concat()));
    streams.push(("bad_checksum_then_valid", [bad_sum, wave].concat()));
    streams.push(("unknown_action", frame(0x7F, 0, 0, 50).to_vec()));
    streams.push(("action_zero_is_unknown", frame(0, 1, 1, 50).to_vec()));
    streams.push(("bad_zone", frame(3, 3, 0, 50).to_vec()));
    streams.push(("bad_distance", frame(3, 0, 3, 50).to_vec()));
    streams.push(("confidence_over_100", frame(3, 0, 0, 101).to_vec()));
    streams.push(("wrong_start_byte_ignored", bad_start.to_vec()));
    streams.push(("truncated_frame_swallows_next_start", [wave[..4].to_vec(), nod.to_vec()].concat()));

    let rows: Vec<String> = streams
        .iter()
        .map(|(name, bytes)| {
            format!(
                "  {{\"name\":\"{}\",\"bytes\":\"{}\",\"expect\":[{}]}}",
                name,
                hex(bytes),
                quote_list(&run_stream(bytes))
            )
        })
        .collect();

    let errors: Vec<String> = [
        crate::wire::PacketError::WrongLength,
        crate::wire::PacketError::BadStart,
        crate::wire::PacketError::BadChecksum,
        crate::wire::PacketError::UnknownAction,
        crate::wire::PacketError::BadZone,
        crate::wire::PacketError::BadDistance,
        crate::wire::PacketError::BadConfidence,
    ]
    .iter()
    .map(|e| format!("\"{}\":{}", e.name(), e.code()))
    .collect();

    format!(
        "{{\"format\":1,\"error_codes\":{{{}}},\"streams\":[\n{}\n]}}\n",
        errors.join(","),
        rows.join(",\n")
    )
}

struct Scenario {
    name: &'static str,
    inputs: Vec<(i64, Packet)>,
    end_ms: i64,
}

fn pk(action: Action, zone: Zone) -> Packet {
    Packet::new(
        Key {
            action,
            zone,
            distance: Distance::Medium,
        },
        90,
    )
    .expect("supported action")
}

fn scenarios() -> Vec<Scenario> {
    let mut list = Vec::new();

    list.push(Scenario {
        name: "single_wave_starts_immediately",
        inputs: vec![(10, pk(Action::Waving, Zone::Left))],
        end_ms: 100,
    });
    list.push(Scenario {
        name: "second_event_waits_for_rest",
        inputs: vec![
            (0, pk(Action::Waving, Zone::Center)),
            (2000, pk(Action::Appeared, Zone::Center)),
        ],
        end_ms: 4000,
    });
    list.push(Scenario {
        name: "waiting_event_expires_after_2s",
        inputs: vec![
            (0, pk(Action::Waving, Zone::Center)),
            (100, pk(Action::Left, Zone::Center)),
        ],
        end_ms: 4000,
    });
    list.push(Scenario {
        name: "same_action_replaces_waiting_one",
        inputs: vec![
            (0, pk(Action::Appeared, Zone::Center)),
            (500, pk(Action::Nodding, Zone::Left)),
            (600, pk(Action::Nodding, Zone::Right)),
        ],
        end_ms: 4000,
    });
    list.push(Scenario {
        name: "full_queue_drops_oldest",
        inputs: vec![
            (0, pk(Action::Appeared, Zone::Center)),
            (100, pk(Action::Nodding, Zone::Center)),
            (200, pk(Action::ShakingHead, Zone::Center)),
            (300, pk(Action::ReachingOut, Zone::Center)),
            (400, pk(Action::LookedLeft, Zone::Center)),
        ],
        end_ms: 6000,
    });
    list.push(Scenario {
        name: "limit_12_patterns_per_minute",
        inputs: (0..=27)
            .map(|k| (k * 2150, pk(Action::Appeared, Zone::Center)))
            .collect(),
        end_ms: 61_000,
    });
    // Boundary: a queued event that is exactly 2000 ms old at the moment the rest ends.
    list.push(Scenario {
        name: "rest_ends_exactly_when_event_is_2s_old",
        inputs: vec![
            (0, pk(Action::Waving, Zone::Center)),
            (1000, pk(Action::Left, Zone::Center)),
        ],
        end_ms: 3500,
    });
    list
}

pub fn scheduler_vectors_json(limits: &SafetyLimits) -> String {
    let mut rows = Vec::new();
    for s in scenarios() {
        let inputs: Vec<String> = s
            .inputs
            .iter()
            .map(|(t, p)| {
                format!(
                    "{{\"t_ms\":{},\"packet\":\"{}\"}}",
                    t,
                    hex(&p.encode())
                )
            })
            .collect();
        let starts: Vec<String> = run_schedule(&s.inputs, s.end_ms, limits)
            .iter()
            .map(|(t, key)| format!("{{\"t_ms\":{},{}}}", t, key_fields(key)))
            .collect();
        rows.push(format!(
            "  {{\"name\":\"{}\",\"end_ms\":{},\"inputs\":[{}],\"starts\":[{}]}}",
            s.name,
            s.end_ms,
            inputs.join(","),
            starts.join(",")
        ));
    }
    format!(
        "{{\"format\":1,\"poll_period_ms\":1,\"rules\":{{\"rest_gap_ms\":{},\"max_age_ms\":{},\"max_per_minute\":{},\"max_queue\":{}}},\"scenarios\":[\n{}\n]}}\n",
        (limits.min_pattern_gap_s * 1000.0).round() as i64,
        (limits.max_age_s * 1000.0).round() as i64,
        limits.max_patterns_per_minute,
        limits.max_queue,
        rows.join(",\n")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rom_image_has_one_word_per_slot_word() {
        let rom = pattern_rom_hex(&SafetyLimits::default());
        let words = rom.lines().filter(|l| !l.starts_with("//")).count();
        assert_eq!(words, KEY_COUNT * WORDS_PER_KEY);
    }

    #[test]
    fn exports_are_deterministic() {
        let limits = SafetyLimits::default();
        assert_eq!(pattern_vectors_json(&limits), pattern_vectors_json(&limits));
        assert_eq!(scheduler_vectors_json(&limits), scheduler_vectors_json(&limits));
        assert_eq!(packet_vectors_json(), packet_vectors_json());
    }

    #[test]
    fn stream_expectations_make_sense() {
        let out = run_stream(&frame(0x7F, 0, 0, 50));
        assert_eq!(out, vec!["err:unknown_action".to_string()]);
    }
}
